function setLanguage(language) {
  const selected = translations[language] ? language : "en";
  document.documentElement.lang = selected === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[selected][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  localStorage.setItem("siteLanguage", selected);
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const yearElement = document.querySelector("#year");
if (yearElement) yearElement.textContent = new Date().getFullYear();
setLanguage(document.documentElement.dataset.staticLanguage || localStorage.getItem("siteLanguage") || "en");

const siteNav = document.querySelector(".site-nav");
if (siteNav) {
  document.documentElement.classList.add("nav-ready");
  if (!siteNav.id) siteNav.id = "site-navigation";

  const isChinese = document.documentElement.lang.startsWith("zh");
  const menuButton = document.createElement("button");
  menuButton.className = "nav-toggle";
  menuButton.type = "button";
  menuButton.setAttribute("aria-controls", siteNav.id);
  menuButton.setAttribute("aria-expanded", "false");
  menuButton.setAttribute("aria-label", isChinese ? "打开菜单" : "Open menu");
  menuButton.innerHTML = '<span></span><span></span><span></span>';
  siteNav.before(menuButton);

  const closeMenu = () => {
    siteNav.classList.remove("is-open");
    document.body.classList.remove("nav-open");
    menuButton.setAttribute("aria-expanded", "false");
    menuButton.setAttribute("aria-label", isChinese ? "打开菜单" : "Open menu");
  };

  menuButton.addEventListener("click", () => {
    const opening = !siteNav.classList.contains("is-open");
    siteNav.classList.toggle("is-open", opening);
    document.body.classList.toggle("nav-open", opening);
    menuButton.setAttribute("aria-expanded", String(opening));
    menuButton.setAttribute("aria-label", opening ? (isChinese ? "关闭菜单" : "Close menu") : (isChinese ? "打开菜单" : "Open menu"));
  });

  siteNav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && siteNav.classList.contains("is-open")) {
      closeMenu();
      menuButton.focus();
    }
  });
  window.addEventListener("resize", () => {
    if (window.innerWidth > 760) closeMenu();
  });
}

const fictionSearchInput = document.querySelector("#fiction-search-input");
const fictionCatalog = document.querySelector("#fiction-catalog");

if (fictionSearchInput && fictionCatalog) {
  const stories = [...fictionCatalog.querySelectorAll(".published-work")];
  const groups = [];
  let currentGroup;

  [...fictionCatalog.children].forEach((element) => {
    if (element.classList.contains("fiction-group-title")) {
      currentGroup = { heading: element, stories: [] };
      groups.push(currentGroup);
    } else if (element.classList.contains("published-work") && currentGroup) {
      currentGroup.stories.push(element);
      element.dataset.searchText = `${currentGroup.heading.textContent} ${element.textContent}`
        .normalize("NFKC")
        .toLocaleLowerCase();
    }
  });

  const status = document.querySelector("#fiction-search-status");
  const emptyMessage = fictionCatalog.querySelector(".fiction-empty");
  const isChinese = document.documentElement.lang.startsWith("zh");
  const viewButtons = [...document.querySelectorAll("[data-fiction-view]")];

  const setFictionView = (view) => {
    const selectedView = view === "list" ? "list" : "cards";
    fictionCatalog.classList.toggle("is-list-view", selectedView === "list");
    viewButtons.forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.fictionView === selectedView));
    });
    localStorage.setItem("fictionView", selectedView);
  };

  viewButtons.forEach((button) => {
    button.addEventListener("click", () => setFictionView(button.dataset.fictionView));
  });
  const requestedView = new URLSearchParams(window.location.search).get("view");
  setFictionView(requestedView || localStorage.getItem("fictionView") || "cards");

  const updateFictionResults = () => {
    const query = fictionSearchInput.value.trim().normalize("NFKC").toLocaleLowerCase();
    let visibleCount = 0;

    stories.forEach((story) => {
      const matches = !query || story.dataset.searchText.includes(query);
      story.hidden = !matches;
      if (matches) visibleCount += 1;
    });

    groups.forEach((group) => {
      group.heading.hidden = !group.stories.some((story) => !story.hidden);
    });

    emptyMessage.hidden = visibleCount !== 0;
    status.hidden = !query;
    status.textContent = isChinese
      ? `共 ${visibleCount} 篇`
      : `${visibleCount} ${visibleCount === 1 ? "result" : "results"}`;
  };

  fictionSearchInput.addEventListener("input", updateFictionResults);
  fictionSearchInput.addEventListener("search", updateFictionResults);
}

const resourceSearchInput = document.querySelector("#resource-search-input");
const resourceCatalog = document.querySelector("#resource-catalog");

if (resourceSearchInput && resourceCatalog) {
  const groups = [];
  const entries = [];
  const children = [...resourceCatalog.children];

  for (let index = 0; index < children.length; index += 1) {
    const heading = children[index];
    const list = children[index + 1];
    if (!heading.classList.contains("series-heading") || !list?.classList.contains("notes-list")) continue;

    const groupEntries = [...list.querySelectorAll(".note-entry")];
    const groupText = heading.textContent.normalize("NFKC").toLocaleLowerCase();
    groupEntries.forEach((entry) => {
      entry.dataset.searchText = `${groupText} ${entry.textContent}`.normalize("NFKC").toLocaleLowerCase();
      entry.dataset.resourcePath = new URL(entry.querySelector("a").href).pathname;
      entries.push(entry);
    });
    groups.push({ heading, list, entries: groupEntries });
  }

  const status = document.querySelector("#resource-search-status");
  const emptyMessage = resourceCatalog.querySelector(".resource-empty");
  const isChinese = document.documentElement.lang.startsWith("zh");
  let fullTextReady = false;

  const updateResourceResults = () => {
    const query = resourceSearchInput.value.trim().normalize("NFKC").toLocaleLowerCase();
    let visibleCount = 0;

    entries.forEach((entry) => {
      const matches = !query || entry.dataset.searchText.includes(query);
      entry.hidden = !matches;
      if (matches) visibleCount += 1;
    });

    groups.forEach((group) => {
      const hasMatches = group.entries.some((entry) => !entry.hidden);
      group.heading.hidden = !hasMatches;
      group.list.hidden = !hasMatches;
    });

    emptyMessage.hidden = visibleCount !== 0;
    status.hidden = !query;
    if (query && !fullTextReady) {
      status.textContent = isChinese ? "正在搜索全文…" : "Searching full text…";
    } else {
      status.textContent = isChinese
        ? `共 ${visibleCount} 项`
        : `${visibleCount} ${visibleCount === 1 ? "result" : "results"}`;
    }
  };

  resourceSearchInput.addEventListener("input", updateResourceResults);
  resourceSearchInput.addEventListener("search", updateResourceResults);

  fetch("/resource-search-index.json?v=20260920-1")
    .then((response) => {
      if (!response.ok) throw new Error("Resource search index could not be loaded");
      return response.json();
    })
    .then((searchIndex) => {
      entries.forEach((entry) => {
        const pageText = searchIndex[entry.dataset.resourcePath] || "";
        entry.dataset.searchText = `${entry.dataset.searchText} ${pageText}`
          .normalize("NFKC")
          .toLocaleLowerCase();
      });
      fullTextReady = true;
      updateResourceResults();
    })
    .catch(() => {
      fullTextReady = true;
      updateResourceResults();
    });
}

const contactForm = document.querySelector("[data-contact-form]");

if (contactForm) {
  const submitButton = contactForm.querySelector("button[type='submit']");
  const submitLabel = contactForm.querySelector("[data-submit-label]");
  const status = contactForm.querySelector("[data-contact-status]");
  const subjectInput = contactForm.querySelector("[data-contact-subject]");
  const defaultLabel = submitLabel.textContent;

  contactForm.addEventListener("submit", async (event) => {
    event.preventDefault();
    const captchaResponse = contactForm.querySelector('[name="h-captcha-response"]');
    if (!captchaResponse?.value) {
      status.className = "contact-status is-error";
      status.textContent = contactForm.dataset.captchaError;
      return;
    }

    submitButton.disabled = true;
    submitButton.setAttribute("aria-busy", "true");
    submitLabel.textContent = contactForm.dataset.sending;
    status.className = "contact-status";
    status.textContent = "";

    const senderName = contactForm.elements.namedItem("name").value.trim();
    subjectInput.value = `【伏鳞个人网站】${senderName} 的新留言`;

    try {
      const response = await fetch(contactForm.action, {
        method: "POST",
        body: new FormData(contactForm),
        headers: { Accept: "application/json" }
      });
      const result = await response.json();
      if (!response.ok || !result.success) throw new Error(result.message || "Submission failed");

      contactForm.reset();
      if (window.hcaptcha) window.hcaptcha.reset();
      status.classList.add("is-success");
      status.textContent = contactForm.dataset.success;
    } catch (error) {
      status.classList.add("is-error");
      status.textContent = contactForm.dataset.error;
    } finally {
      submitButton.disabled = false;
      submitButton.removeAttribute("aria-busy");
      submitLabel.textContent = defaultLabel;
    }
  });
}
