function setLanguage(language) {
  const selected = translations[language] ? language : "en";
  document.documentElement.lang = selected === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[selected][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const active = button.dataset.lang === selected;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  localStorage.setItem("siteLanguage", selected);
}

document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

const yearElement = document.querySelector("#year");
if (yearElement) yearElement.textContent = new Date().getFullYear();
setLanguage(document.documentElement.dataset.staticLanguage || localStorage.getItem("siteLanguage") || "en");

const siteNav = document.querySelector(".site-nav");
if (siteNav) {
  document.documentElement.classList.add("nav-ready");
  if (!siteNav.id) siteNav.id = "site-navigation";

  const isChinese = document.documentElement.lang.startsWith("zh");
  const menuButton = document.createElement("button");
  menuButton.className = "nav-toggle";
  menuButton.type = "button";
  menuButton.setAttribute("aria-controls", siteNav.id);
  menuButton.setAttribute("aria-expanded", "false");
  menuButton.setAttribute("aria-label", isChinese ? "打开菜单" : "Open menu");
  menuButton.innerHTML = '<span></span><span></span><span></span>';
  siteNav.before(menuButton);

  const closeMenu = () => {
    siteNav.classList.remove("is-open");
    document.body.classList.remove("nav-open");
    menuButton.setAttribute("aria-expanded", "false");
    menuButton.setAttribute("aria-label", isChinese ? "打开菜单" : "Open menu");
  };

  menuButton.addEventListener("click", () => {
    const opening = !siteNav.classList.contains("is-open");
    siteNav.classList.toggle("is-open", opening);
    document.body.classList.toggle("nav-open", opening);
    menuButton.setAttribute("aria-expanded", String(opening));
    menuButton.setAttribute("aria-label", opening ? (isChinese ? "关闭菜单" : "Close menu") : (isChinese ? "打开菜单" : "Open menu"));
  });

  siteNav.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && siteNav.classList.contains("is-open")) {
      closeMenu();
      menuButton.focus();
    }
  });
  window.addEventListener("resize", () => {
    if (window.innerWidth > 760) closeMenu();
  });
}
